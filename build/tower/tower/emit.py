"""Emit one dependency-free C99 translation unit from a `CellSpec`.

The generated file has no includes beyond `<stdint.h>`/`<string.h>`, allocates
nothing, and contains no floating-point type. That last property is not a claim
in a comment — `tower.verify` greps for it, and the generated self-test prints
its own results for a Python gate to cross-check.
"""

from __future__ import annotations

from .spec import CellSpec

__all__ = ["emit_c"]

_TEMPLATE = r'''/* {name} -- generated by tower. DO NOT EDIT.
 *
 * {description}
 *
 * Rendering : {out_name} = ({in_name} - {offset}) * {num} / {den}
 * Basis     : 1/{basis_den} {unit}   (exact: a span of {span_out} {unit}
 *             lands on the lattice, checked before this file was written)
 * Range     : [{out_min}, {out_max}] {unit}
 * Deadband  : {deadband} {unit}, judged in squared integer form
 * Tick      : {tick_ms} ms
 *
 * No floating-point type appears in this file. Nothing here allocates.
 */

#include <stdint.h>
#include <string.h>

#define {CNAME}_OFFSET     ({offset})
#define {CNAME}_NUM        ({num})
#define {CNAME}_DEN        ({den})
#define {CNAME}_OUT_MIN    ({out_min})
#define {CNAME}_OUT_MAX    ({out_max})
#define {CNAME}_DEADBAND   ({deadband})
#define {CNAME}_WINDOW     ({median_window})
#define {CNAME}_TICK_MS    ({tick_ms})

/* ---- moving median ---------------------------------------------------- */
/* An odd window, so the median is always a real sample rather than an
 * average of two -- which would reintroduce a division and a rounding
 * decision on the raw path. Insertion sort on a fixed tiny array. */

typedef struct {{
    int32_t  buf[{CNAME}_WINDOW];
    uint8_t  count;
    uint8_t  head;
}} {cname}_filter_t;

void {cname}_filter_init({cname}_filter_t *f)
{{
    memset(f, 0, sizeof *f);
}}

int32_t {cname}_filter_push({cname}_filter_t *f, int32_t sample)
{{
    int32_t sorted[{CNAME}_WINDOW];
    uint8_t i, j, n;
    int32_t key;

    f->buf[f->head] = sample;
    f->head = (uint8_t)((f->head + 1u) % {CNAME}_WINDOW);
    if (f->count < {CNAME}_WINDOW) {{
        f->count = (uint8_t)(f->count + 1u);
    }}

    n = f->count;
    for (i = 0; i < n; i++) {{
        sorted[i] = f->buf[i];
    }}
    for (i = 1; i < n; i++) {{
        key = sorted[i];
        j = i;
        while (j > 0 && sorted[j - 1] > key) {{
            sorted[j] = sorted[j - 1];
            j--;
        }}
        sorted[j] = key;
    }}
    return sorted[n / 2u];
}}

/* ---- rendering --------------------------------------------------------- */
/* Round half away from zero, symmetric about zero: (2n + d) / 2d with the
 * sign carried out and back. C integer division truncates toward zero, so
 * the sign must be handled explicitly or negative ranges would round the
 * wrong way. */

int32_t {cname}_render(int32_t raw)
{{
    int64_t n = (int64_t)(raw - {CNAME}_OFFSET) * (int64_t){CNAME}_NUM;
    int64_t d = (int64_t){CNAME}_DEN;
    int64_t q;

    if (n >= 0) {{
        q = (2 * n + d) / (2 * d);
    }} else {{
        q = -((-2 * n + d) / (2 * d));
    }}
    if (q < {CNAME}_OUT_MIN) {{ q = {CNAME}_OUT_MIN; }}
    if (q > {CNAME}_OUT_MAX) {{ q = {CNAME}_OUT_MAX; }}
    return (int32_t)q;
}}

/* ---- the deadband judge ------------------------------------------------ */
/* Squared form: WITHIN iff d*d <= D*D. Exact in integers, and it contributes
 * zero comparison error -- there is no square root to be approximate about.
 * Widened to int64_t so a large disagreement cannot overflow the square. */

int {cname}_within(int32_t a, int32_t b)
{{
    int64_t d = (int64_t)a - (int64_t)b;
    int64_t D = (int64_t){CNAME}_DEADBAND;
    return (d * d) <= (D * D);
}}

/* ---- the cell ---------------------------------------------------------- */
/* Reality wins: when the sensor leaves the twin's deadband we SNAP the twin
 * to the sensor and book the drift as debt. The post is the ledger entry --
 * one line, both books. */

typedef struct {{
    {cname}_filter_t filter;
    int32_t  value;
    int32_t  twin;
    uint8_t  twin_known;
    int64_t  snap_debt;
    uint32_t posts;
    uint32_t ticks;
}} {cname}_cell_t;

void {cname}_init({cname}_cell_t *c)
{{
    memset(c, 0, sizeof *c);
    {cname}_filter_init(&c->filter);
}}

/* Feed one raw sample. Returns 1 if this tick posted a snap. */
int {cname}_tick({cname}_cell_t *c, int32_t raw)
{{
    int32_t filtered = {cname}_filter_push(&c->filter, raw);
    int64_t drift;

    c->value = {cname}_render(filtered);
    c->ticks++;

    if (!c->twin_known) {{
        c->twin = c->value;
        c->twin_known = 1u;
        c->posts++;
        return 1;
    }}
    if (!{cname}_within(c->value, c->twin)) {{
        drift = (int64_t)c->value - (int64_t)c->twin;
        if (drift < 0) {{ drift = -drift; }}
        c->snap_debt += drift;
        c->twin = c->value;
        c->posts++;
        return 1;
    }}
    return 0;
}}
'''

_SELFTEST = r'''
/* ---- self-test --------------------------------------------------------- */
/* Prints one RESULT line per vector. `tower.verify` compiles this, runs it,
 * and cross-checks every line against an independent Python model. */
#ifdef {CNAME}_SELFTEST
#include <stdio.h>

int main(void)
{{
    int32_t vectors[] = {{ {vectors} }};
    size_t k, n = sizeof vectors / sizeof vectors[0];
    {cname}_cell_t cell;

    for (k = 0; k < n; k++) {{
        printf("RENDER %d %d\n", (int)vectors[k], (int){cname}_render(vectors[k]));
    }}
    for (k = 0; k < n; k++) {{
        printf("WITHIN %d %d %d\n", (int)vectors[k], (int)({CNAME}_DEADBAND),
               {cname}_within(vectors[k], 0));
    }}
    {cname}_init(&cell);
    for (k = 0; k < n; k++) {{
        int snapped = {cname}_tick(&cell, vectors[k]);
        printf("TICK %d %d %d %lld\n", (int)vectors[k], (int)cell.value,
               snapped, (long long)cell.snap_debt);
    }}
    printf("SUMMARY posts=%u ticks=%u debt=%lld\n",
           cell.posts, cell.ticks, (long long)cell.snap_debt);
    return 0;
}}
#endif
'''


def emit_c(spec: CellSpec, vectors: list[int] | None = None) -> str:
    """Render the C translation unit for `spec`."""
    vec = vectors if vectors is not None else []
    body = _TEMPLATE.format(
        name=spec.name, cname=spec.cname, CNAME=spec.cname.upper(),
        description=spec.description or "(no description)",
        in_name=spec.in_name, out_name=spec.out_name, unit=spec.unit,
        offset=spec.offset, num=spec.num, den=spec.den,
        basis_den=spec.basis_den, span_out=spec.out_max - spec.out_min,
        out_min=spec.out_min, out_max=spec.out_max,
        deadband=spec.deadband, median_window=spec.median_window,
        tick_ms=spec.tick_ms,
    )
    body += _SELFTEST.format(
        cname=spec.cname, CNAME=spec.cname.upper(),
        vectors=", ".join(str(v) for v in vec),
    )
    return body
